const assert=require('node:assert/strict');
module.exports=async function checkManagement(page) {
  const row=id=>page.locator('#worker-list button').filter({hasText:id});
  await row('demo-summary').click();
  const fields={};
  for(const id of ['edit-artifact-id','edit-artifact-hash','edit-entrypoint']) {
    assert(await page.locator('#'+id).evaluate(el=>el.readOnly));
    fields[id]=await page.locator('#'+id).inputValue();
  }
  await page.locator('#worker-editor-close').click();
  await page.locator('#worker-create').click();
  await page.locator('#edit-worker-id').fill('browser-managed');
  for(const [id,value] of Object.entries(fields))await page.locator('#'+id).fill(value);
  await page.locator('#edit-configuration').fill('[]');
  await page.locator('#worker-save').click();
  await page.waitForFunction(()=>document.getElementById('worker-edit-status').textContent.includes('JSON object'));
  await page.locator('#edit-configuration').fill('{"sample":true}');
  await page.locator('#worker-save').click();
  await page.locator('#worker-editor').waitFor({state:'hidden'});
  assert((await row('browser-managed').textContent()).includes('پیکربندی‌شده'));
  await row('browser-managed').click();
  await page.locator('#worker-toggle').click();await page.locator('#worker-confirm-submit').click();
  await page.locator('#worker-editor').waitFor({state:'hidden'});
  assert((await row('browser-managed').textContent()).includes('فعال'));
  await row('browser-managed').click();
  await page.locator('#worker-toggle').click();await page.locator('#worker-confirm-submit').click();
  await page.locator('#worker-editor').waitFor({state:'hidden'});
  await row('browser-managed').click();
  await page.locator('#edit-schedule').selectOption('interval');
  await page.locator('#edit-interval').fill('60');
  await page.locator('#edit-configuration').fill('{"updated":2}');
  await page.locator('#worker-save').click();await page.locator('#worker-editor').waitFor({state:'hidden'});
  await row('browser-managed').click();
  assert.equal(await page.locator('#edit-schedule').inputValue(),'interval');
  assert.equal(await page.locator('#edit-interval').inputValue(),'60');
  assert.deepEqual(JSON.parse(await page.locator('#edit-configuration').inputValue()),{updated:2});
  await page.locator('#worker-delete').click();
  await page.locator('#worker-confirm-id').fill('wrong');await page.locator('#worker-confirm-submit').click();
  await page.waitForFunction(()=>document.getElementById('worker-confirm-status').textContent.includes('شناسه دقیق'));
  await page.locator('#worker-confirm-id').fill('browser-managed');await page.locator('#worker-confirm-submit').click();
  await page.locator('#worker-editor').waitFor({state:'hidden'});
  assert.equal(await row('browser-managed').count(),0);
  await page.locator('#history-worker').fill('no-matching-worker');
  assert((await page.locator('#account-executions').textContent()).includes('فیلتر'));
  await page.locator('#history-worker').fill('demo-summary');
  await page.locator('#history-status').selectOption('failed');
  assert((await page.locator('#account-executions').textContent()).includes('ناموفق'));
  assert(!(await page.locator('#account-executions').textContent()).includes('· موفق ·'));
  await page.locator('#history-worker').fill('');await page.locator('#history-status').selectOption('');
  await row('demo-summary').click();
  await page.locator('#worker-editor-close').click();
};
